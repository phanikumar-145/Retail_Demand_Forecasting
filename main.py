"""
main.py
=======
Retail Demand Forecasting and Replenishment System - full pipeline.

Run this ONE file and the whole project executes end to end:

    python main.py

    python main.py --regenerate-data     # rebuild the synthetic dataset first
    python main.py --lead-time 5         # use a different supplier lead time

Steps executed
    1. Load dataset            (creates a synthetic one if none exists)
    2. Preprocess data         (types, duplicates, missing, invalid values)
    3. EDA + charts
    4. Feature engineering     (calendar, lag, rolling features - no leakage)
    5. Train + compare models  (Linear Regression, Random Forest, Tuned RF)
    6. Evaluate                (metrics, category errors, charts)
    7. Forecast next 7 days
    8. Reorder recommendations (expected demand + safety stock - current stock)
"""

import argparse
import sys
import time
import traceback

import pandas as pd

from src import config
from src import data_preprocessing
from src import eda
from src import evaluate_model
from src import feature_engineering
from src import forecasting
from src import replenishment
from src import train_model


def banner(text: str) -> None:
    """Print a clear step banner so the console output is easy to follow."""
    line = "=" * 78
    print(f"\n{line}\n{text}\n{line}")


def parse_arguments() -> argparse.Namespace:
    """Optional command-line options (all have safe defaults)."""
    parser = argparse.ArgumentParser(
        description="Retail Demand Forecasting and Replenishment System"
    )
    parser.add_argument(
        "--regenerate-data",
        action="store_true",
        help="Ignore the existing raw CSV and generate a new synthetic dataset.",
    )
    parser.add_argument(
        "--lead-time",
        type=int,
        default=config.DEFAULT_LEAD_TIME_DAYS,
        help=f"Supplier lead time in days (default: {config.DEFAULT_LEAD_TIME_DAYS}).",
    )
    return parser.parse_args()


def main() -> int:
    """Run the full pipeline. Returns 0 on success, 1 on failure."""
    start_time = time.time()
    args = parse_arguments()

    banner("RETAIL DEMAND FORECASTING AND REPLENISHMENT SYSTEM")
    print("Dataset note: the bundled dataset is SYNTHETIC (generated by code),")
    print("not real business data. Replace data/raw/retail_sales.csv with a real")
    print("export in the same format to use your own numbers.")
    config.ensure_directories()

    try:
        # ---------------- STEP 1 + 2: load and preprocess ----------------
        banner("STEP 1-2: LOAD AND PREPROCESS DATA")
        cleaned_df = data_preprocessing.run_preprocessing(
            regenerate=args.regenerate_data
        )
        print(f"\nCleaned data: {len(cleaned_df):,} rows")

        # ---------------- STEP 3: EDA ------------------------------------
        banner("STEP 3: EXPLORATORY DATA ANALYSIS")
        eda.run_full_eda(cleaned_df)

        # ---------------- STEP 4: feature engineering --------------------
        banner("STEP 4: FEATURE ENGINEERING")
        feature_df = feature_engineering.build_features(cleaned_df, save=True)
        X_train, X_test, y_train, y_test, train_df, test_df = (
            feature_engineering.chronological_split(feature_df)
        )

        # ---------------- STEP 5: train and compare models ---------------
        banner("STEP 5: TRAIN AND COMPARE MODELS")
        results_df, trained_models, best_model_name, best_model = (
            train_model.train_and_compare(X_train, X_test, y_train, y_test)
        )
        train_model.save_evaluation_report(results_df)
        train_model.save_model_artifacts(
            best_model, best_model_name, results_df, train_df, test_df
        )

        banner("MODEL COMPARISON (test set)")
        print(results_df.to_string(index=False))

        # ---------------- STEP 6: evaluation -----------------------------
        banner("STEP 6: EVALUATE THE SELECTED MODEL")
        category_table = evaluate_model.run_evaluation(
            results_df, trained_models, best_model_name, train_df, test_df
        )

        # ---------------- STEP 7: future forecasts -----------------------
        banner("STEP 7: FORECAST THE NEXT 7 DAYS")
        forecasts = forecasting.forecast_future_demand(
            cleaned_df=cleaned_df,
            model=best_model,
            horizon=config.FORECAST_HORIZON,
            feature_columns=config.FEATURE_COLUMNS,
        )
        forecasting.save_forecasts(forecasts)
        forecasting.plot_forecasts(forecasts, cleaned_df)
        print("\nFirst rows of the forecast:")
        print(forecasts.head(8).to_string(index=False))

        # ---------------- STEP 8: reorder recommendations ----------------
        banner("STEP 8: REPLENISHMENT RECOMMENDATIONS")
        reorder_table = replenishment.calculate_reorder_recommendations(
            forecasts=forecasts,
            cleaned_df=cleaned_df,
            lead_time_days=args.lead_time,
        )
        replenishment.save_reorder_recommendations(reorder_table)
        replenishment.explain_with_example(reorder_table)
        replenishment.plot_stock_vs_reorder(reorder_table)
        print("\nTop 5 reorder recommendations:")
        print(reorder_table.head(5).to_string(index=False))

        # ---------------- DONE -------------------------------------------
        elapsed = time.time() - start_time
        banner("PIPELINE COMPLETED SUCCESSFULLY")
        print(f"Total runtime: {elapsed / 60:.1f} minutes")
        print(f"\nBest model            : {best_model_name}")
        print(f"Test MAE              : {results_df.iloc[0]['MAE']:.3f} units")
        print(f"Test RMSE             : {results_df.iloc[0]['RMSE']:.3f} units")
        print(f"Test R2               : {results_df.iloc[0]['R2']:.4f}")
        print(f"Forecast rows         : {len(forecasts):,}")
        print(f"Products to reorder   : {int(reorder_table['needs_reorder'].sum())}")
        print("\nOutput files:")
        for path in [
            config.FORECAST_FILE,
            config.EVALUATION_FILE,
            config.CATEGORY_ERROR_FILE,
            config.REORDER_FILE,
            config.MODEL_FILE,
        ]:
            print(f"  - {path.relative_to(config.BASE_DIR)}")
        print(f"  - charts in {(config.CHARTS_DIR).relative_to(config.BASE_DIR)}/")
        print("\nNext step: view the dashboard with 'streamlit run app.py'")
        return 0

    except FileNotFoundError as error:
        print(f"\n[FILE ERROR] {error}")
        print("Check that data/raw/retail_sales.csv exists, or run with --regenerate-data.")
        return 1
    except ValueError as error:
        print(f"\n[DATA ERROR] {error}")
        print("The dataset does not look the way the pipeline expects.")
        return 1
    except Exception:
        print("\n[UNEXPECTED ERROR] The pipeline stopped. Full details below:")
        traceback.print_exc()
        return 1


if __name__ == "__main__":
    sys.exit(main())
